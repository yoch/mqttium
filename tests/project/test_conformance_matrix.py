"""The generated conformance matrix matches the tree it describes.

``docs/conformance-matrix.md`` and ``docs/spec/conformance-matrix.json`` are
generated by ``tools/build_conformance_matrix.py``. A test that gains, loses or
misquotes a statement label changes them, so a stale copy fails here instead of
silently describing another tree.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
_SPEC = importlib.util.spec_from_file_location(
    "build_conformance_matrix", ROOT / "tools" / "build_conformance_matrix.py"
)
assert _SPEC is not None and _SPEC.loader is not None
matrix = importlib.util.module_from_spec(_SPEC)
sys.modules["build_conformance_matrix"] = matrix
_SPEC.loader.exec_module(matrix)


def test_generated_matrix_is_current() -> None:
    generated_json, generated_page, problems = matrix.build()
    assert problems == []
    assert matrix.MATRIX_JSON.read_text(encoding="utf-8") == generated_json, (
        "run python tools/build_conformance_matrix.py"
    )
    assert matrix.MATRIX_PAGE.read_text(encoding="utf-8") == generated_page, (
        "run python tools/build_conformance_matrix.py"
    )
    assert matrix.main(["--check"]) == 0


def test_every_statement_is_classified_and_keyed_by_version() -> None:
    statements = matrix.load_statements()
    assert matrix.apply_applicability(statements) == []
    assert len(statements) == 139 + 251
    assert {statement.applicability for statement in statements.values()} == set(matrix.CLASSES)
    # A statement naming both parties cannot be classified by a mention.
    for statement in statements.values():
        if matrix.names_both_parties(statement.text):
            assert statement.basis == "reviewed", (statement.version, statement.label)
    # The same label is a different statement in each specification.
    shared = {label for _v, label in statements if ("3.1.1", label) in statements} & {
        label for _v, label in statements if ("5.0", label) in statements
    }
    assert len(shared) == 119
    differing = [
        label
        for label in shared
        if statements[("3.1.1", label)].text != statements[("5.0", label)].text
    ]
    assert len(differing) > 100


def test_reviewed_applicability_names_only_real_statements() -> None:
    statements = matrix.load_statements()
    reviewed = json.loads(matrix.APPLICABILITY.read_text(encoding="utf-8"))["reviewed"]
    assert set(reviewed) == set(matrix.VERSIONS)
    for version, labels in reviewed.items():
        for label, value in labels.items():
            assert (version, label) in statements, (version, label)
            assert value in matrix.CLASSES, (version, label)


def test_evidence_points_at_tests_that_exist() -> None:
    statements = matrix.load_statements()
    matrix.apply_applicability(statements)
    assert matrix.collect_evidence(statements) == []
    verified = [s for s in statements.values() if s.evidence == "verified"]
    assert len(verified) >= 20, "the quotation scan found almost nothing; it is broken"
    for statement in verified:
        for reference in statement.verified_by:
            path, _, name = reference.partition("::")
            source = (ROOT / path).read_text(encoding="utf-8")
            assert f"def {name}(" in source, reference


def test_a_quotation_is_attributed_to_the_version_it_reproduces() -> None:
    statements = matrix.load_statements()
    v311 = statements[("3.1.1", "MQTT-3.1.2-22")]
    v5 = statements[("5.0", "MQTT-3.1.2-22")]
    assert v311.text != v5.text
    assert matrix.quote_matches(v311.text, v311.text)
    assert not matrix.quote_matches(v311.text, v5.text)
    assert not matrix.quote_matches("", v5.text)
    # A quotation that stops early, or lifts a few words, proves nothing: the
    # part left out is often the obligation itself.
    assert not matrix.quote_matches(v5.text[:60], v5.text)
    assert not matrix.quote_matches("A", v5.text)
    assert not matrix.quote_matches(" ".join(v5.text.split()[3:9]), v5.text)
    assert matrix.quote_matches(v5.text.upper().replace(" ", "\n"), v5.text)


def _verified_from(source: str, name: str = "tests/unit/test_planted.py") -> set[tuple[str, str]]:
    statements = matrix.load_statements()
    return matrix._verify_quotations(source, name, statements)


def test_only_a_test_that_runs_counts_as_evidence() -> None:
    statements = matrix.load_statements()
    text = statements[("5.0", "MQTT-2.2.1-2")].text
    doc = f'    """[MQTT-2.2.1-2] {text}"""\n'
    body = "    assert True\n"
    ran = {("5.0", "MQTT-2.2.1-2")}
    assert _verified_from(f"def test_ok():\n{doc}{body}") == ran
    assert _verified_from(f"async def test_ok():\n{doc}{body}") == ran
    # Never run, never collected, or nothing but a docstring.
    assert _verified_from(f"@pytest.mark.skip\ndef test_skipped():\n{doc}{body}") == set()
    assert _verified_from(f"@pytest.mark.xfail(strict=True)\ndef test_x():\n{doc}{body}") == set()
    assert _verified_from(f"def test_empty():\n{doc}") == set()
    nested = f"def helper():\n    def test_inner():\n    {doc}    {body}"
    assert _verified_from(nested) == set()
    assert _verified_from(f"def test_ok():\n{doc}{body}", "tests/helpers.py") == set()


def test_a_test_named_for_one_version_is_evidence_for_that_version_only() -> None:
    statements = matrix.load_statements()
    label = next(
        label
        for (version, label), statement in sorted(statements.items())
        if version == "5.0"
        and ("3.1.1", label) in statements
        and matrix.quote_matches(statement.text, statements[("3.1.1", label)].text)
    )
    text = statements[("5.0", label)].text
    source = 'def {name}():\n    """[{label}] {text}"""\n    assert True\n'
    both = {("3.1.1", label), ("5.0", label)}
    assert _verified_from(source.format(name="test_shared", label=label, text=text)) == both
    assert _verified_from(source.format(name="test_mqtt5_x", label=label, text=text)) == {
        ("5.0", label)
    }
    assert _verified_from(source.format(name="test_mqtt311_x", label=label, text=text)) == {
        ("3.1.1", label)
    }
